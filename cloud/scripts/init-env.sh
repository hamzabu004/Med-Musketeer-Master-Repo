#!/usr/bin/env bash
set -Eeuo pipefail

# Creates a .env with fresh random secrets for the cloud stack. Refuses to overwrite an existing
# file: the ZITADEL masterkey cannot change once ZITADEL has been initialised with it.
# Usage: scripts/init-env.sh [path]   (default: cloud/.env)

readonly CLOUD_DIR="$(cd "$(dirname "$0")/.." && pwd)"
# Resolve the target before changing directory, so a relative path means the caller's.
if [[ $# -ge 1 ]]; then
    TARGET="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
else
    TARGET="$CLOUD_DIR/.env"
fi
readonly TARGET
cd "$CLOUD_DIR"

if [[ -e "$TARGET" ]]; then
    printf '%s already exists; not overwriting it.\n' "$TARGET" >&2
    exit 1
fi

secret() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1" || true; }

umask 077
{
    printf '# Generated by scripts/init-env.sh on %s. Never commit this file.\n' "$(date -Is)"
    grep -E '^[A-Z_]+=' .env.example | grep -Ev '_(PASSWORD|MASTERKEY|SECRET|COOKIE)=' || true
    printf 'POSTGRES_ADMIN_PASSWORD=%s\n' "$(secret 32)"
    printf 'ZITADEL_DB_PASSWORD=%s\n' "$(secret 32)"
    printf 'MM_MIGRATOR_PASSWORD=%s\n' "$(secret 32)"
    printf 'MM_API_PASSWORD=%s\n' "$(secret 32)"
    printf 'ZITADEL_MASTERKEY=%s\n' "$(secret 32)"
    # ZITADEL's default password policy needs upper and lower case, a digit and a symbol.
    printf 'ZITADEL_ADMIN_PASSWORD=%s\n' "$(secret 24)aA1!"
    printf 'LOGIN_SESSION_COOKIE_SECRET=%s\n' "$(secret 48)"
    printf 'EMQX_DASHBOARD_PASSWORD=%s\n' "$(secret 24)"
    printf 'EMQX_HOOK_SECRET=%s\n' "$(secret 48)"
    printf 'EMQX_ADAPTER_PASSWORD=%s\n' "$(secret 32)"
    printf 'EMQX_NODE_COOKIE=%s\n' "$(secret 32)"
    printf 'INGEST_SECRET=%s\n' "$(secret 48)"
} > "$TARGET"

printf 'Wrote %s\n' "$TARGET"
