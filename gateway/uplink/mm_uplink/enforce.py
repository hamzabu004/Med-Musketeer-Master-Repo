"""Enforcing the revocation list on the gateway's Mosquitto (stack.md, Iteration 4 Slice 0).

The wearable listener's ACL file is generated: the fixed-path topic patterns, then a
`user <device id>` / `topic deny #` block per listed wearable. Mosquitto reloads it on SIGHUP. A
listed wearable's publishes are refused and nothing is delivered to it, on a connection that is
already open too; the connection itself stays open (stock Mosquitto cannot drop a client
identified by its certificate). The broker sees the certificate CN only, so the list's
`certificates` entries are enforced by the cloud, not here.

The uplink runs as the `mosquitto` user, so the file is owned by it with mode 0600, as Mosquitto
2.x asks (it warns that later versions refuse anything else), and it may signal the broker.
"""
import logging
import os
import signal
import subprocess
from collections.abc import Callable
from pathlib import Path

from mm_uplink import files
from mm_uplink.revocations import is_device_id

log = logging.getLogger(__name__)

# Kept in step with tools/Fixed-Gateway-Setup/setup_mosquitto.sh, which writes the first file
# (a test compares them).
PATTERNS = """\
# Wearables: username = cert CN = device_id
pattern write mm/fixed/%u/telemetry
pattern write mm/fixed/%u/alert
pattern write mm/fixed/%u/status
pattern write mm/fixed/%u/command_ack
pattern read  mm/fixed/%u/command
"""


def render(listing: dict | None) -> str:
    if listing is None:
        return PATTERNS
    blocks = []
    for device_id in sorted({entry["device_id"] for entry in listing["devices"]}):
        if not is_device_id(device_id):  # parse() already refuses these; never write one
            raise ValueError(f"not a device id: {device_id!r}")
        blocks.append(f"\nuser {device_id}\ntopic deny #\n")
    header = f"\n# Revocation list version {listing['version']} (generated by mm-uplink; do not edit)\n"
    return PATTERNS + header + "".join(blocks)


def sighup_from_pid_file(pid_file: Path) -> Callable[[], None]:
    def reload() -> None:
        os.kill(int(pid_file.read_text().split()[0]), signal.SIGHUP)
    return reload


def run_command(command: tuple[str, ...]) -> Callable[[], None]:
    def reload() -> None:
        subprocess.run(command, check=True, capture_output=True, timeout=15)
    return reload


class Enforcer:
    def __init__(self, acl_file: Path, reload: Callable[[], None]):
        self.acl_file = acl_file
        self.reload = reload
        self.enforced_version: int | None = None  # the version the broker has loaded
        self._unloaded = False  # the file changed but the reload has not succeeded yet

    @property
    def pending(self) -> bool:
        return self._unloaded

    def apply(self, listing: dict | None) -> bool:
        """Brings the ACL file and the broker in line with `listing`; False if the reload failed
        (the caller retries)."""
        text = render(listing)
        try:
            current = self.acl_file.read_text() if self.acl_file.exists() else None
            if current != text:
                files.replace(self.acl_file, text)
                self._unloaded = True
            if self._unloaded:
                self.reload()
                self._unloaded = False
                log.info("broker ACL reloaded: %s wearables refused", text.count("\nuser "))
        except Exception as error:  # noqa: BLE001 - logged; retried by the uplink
            log.error("broker ACL not applied (retrying): %s", error)
            return False
        self.enforced_version = listing["version"] if listing else None
        return True
